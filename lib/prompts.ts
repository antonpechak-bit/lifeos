export function buildSystemPrompt(prevStateMap?: string | null): string {
  if (!prevStateMap) return SYSTEM_PROMPT
  return `${SYSTEM_PROMPT}

КОНТЕКСТ — ПРЕДЫДУЩАЯ КАРТА СОСТОЯНИЯ ЭТОГО ПОЛЬЗОВАТЕЛЯ:
---
${prevStateMap}
---
Учитывай её в разговоре: можешь мягко упоминать прошлые приоритеты, замечать что звучит иначе, чем раньше.

При генерации новой State Map добавь секцию ИЗМЕНЕНИЯ в конце блока (перед [STATE_MAP_END]) — только если разговор дал для этого материал. Если сдвигов не видно или данных мало — секцию пропусти, не выдумывай наполнение ради формата.

Когда секция есть, используй нейтральные гештальт-формулировки — без оценки «лучше/хуже»:
• что сдвинулось или ощущается иначе
• что появилось или ушло
• что осталось прежним

Эпистемическая калибровка: подавай наблюдения пропорционально уверенности. Если между картами прошло мало времени или разговор не дал ясных данных — формулируй осторожно («похоже, наметилось…», «возможно, сдвинулось…»). Не делай diff-таблицу «было X — стало Y». Это живое наблюдение, приглашение заметить — не отчёт о прогрессе.`
}
